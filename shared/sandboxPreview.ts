/**
 * Sandbox-hosted previews. SpacetimeDB is the only application server: a procedure pushes the
 * saved draft into an E2B sandbox whose baked-in agent builds and serves it on its own origin.
 * Pure helpers with an injected HTTP transport so tests never reach E2B.
 */
import type { TargetStack, WorkspaceFile } from './stackAdapters';
import { selectStackAdapter } from './stackAdapters';

export type PreviewKind = 'react' | 'blazor';
export type PreviewHttp = (request: { url: string; method: 'POST' | 'DELETE'; headers: Record<string, string>; body?: string; timeoutMs: number }) => { status: number; body: string };
export type SandboxLease = { sandboxId: string; writeKey: string; capability: string; host: string };

export const PREVIEW_PORT = 8080;
export const PREVIEW_IDLE_SECONDS = 600;
const API = 'https://api.e2b.app';
const DOMAIN = 'e2b.app';
const entries: Record<PreviewKind, string> = { react: 'examples/Preview.tsx', blazor: 'Examples/Preview.razor' };

export const previewMessages = {
  unconfigured: 'Previews are not configured. The operator must set E2B_API_KEY and preview template IDs.',
  unsupported: 'Unsupported target stack: previews support React + TypeScript or Blazor projects. Update the framework and language in project Settings.',
  create: 'Preview sandbox could not be started. Try again shortly.',
  quota: 'Preview sandbox limit or credits reached. The operator must check the E2B account.',
  agent: 'Preview sandbox did not accept the draft. Try again.',
} as const;

export function previewKind(target: TargetStack): PreviewKind | undefined {
  const id = selectStackAdapter(target)?.id;
  return id === 'react-tailwind-shadcn' ? 'react' : id === 'blazor-bootstrap' ? 'blazor' : undefined;
}

/**
 * Returns the files to build. A hand-written preview entry is used as-is; otherwise a host entry is
 * generated (never saved to the draft). It prefers an example/demo/preview file at any depth, which renders the
 * component with sample props, and otherwise renders the component's own file without props.
 */
export function withPreviewEntry(kind: PreviewKind, files: WorkspaceFile[], componentName: string): WorkspaceFile[] {
  if (files.some(file => file.path === entries[kind])) return files;
  // A nested Blazor preview already declaring the host's entry namespace is the entry; generating another would clash.
  if (kind === 'blazor' && files.some(file => /(^|\/)Preview\.razor$/i.test(file.path) && /@namespace\s+ComPlixPreview\.Library\.Examples\s*$/m.test(file.content))) return files;
  const name = componentName.replace(/[^A-Za-z0-9_]/g, '').slice(0, 80);
  if (kind === 'react') {
    if (!files.some(file => /\.tsx$/i.test(file.path))) throw new Error('No React component (.tsx) file found to preview.');
    return [...files, { path: entries.react, content: reactEntry(name) }];
  }
  if (!files.some(file => /\.razor$/i.test(file.path))) throw new Error('No Blazor component (.razor) file found to preview.');
  return [...files, { path: entries.blazor, content: blazorEntry(name) }];
}

function reactEntry(name: string) {
  return `// Generated by ComPlix for preview only; not part of the draft.
import { Component, type ComponentType, type ReactNode } from 'react';

const modules = import.meta.glob<Record<string, unknown>>(['../**/*.tsx', '!./Preview.tsx', '!../**/*.test.tsx', '!../**/*.stories.tsx'], { eager: true });
const wanted = ${JSON.stringify(name)}.toLowerCase();
const isComponent = (value: unknown) => typeof value === 'function' || (!!value && typeof value === 'object' && '$$typeof' in (value as object));
function score(path: string) {
  const base = (path.split('/').pop() ?? '').replace(/\\.tsx$/i, '').toLowerCase();
  return (isExample(path) ? 8 : 0) + (wanted && base === wanted ? 4 : 0) + (wanted && path.toLowerCase().includes('/' + wanted) ? 2 : 0) + (/\\/common\\//i.test(path) ? 1 : 0);
}
// Example/demo/preview files pass sample props, so they outrank the bare component.
function isExample(path: string) { return /\\/(examples?|demos?)\\//i.test(path) || /(preview|example|demo)\\.tsx$/i.test(path); }
function pick(): { path: string; Target: ComponentType } | undefined {
  for (const [path, mod] of Object.entries(modules).sort(([a], [b]) => score(b) - score(a))) {
    const named = Object.entries(mod).find(([key]) => key.toLowerCase() === wanted)?.[1];
    const fallback = Object.entries(mod).find(([key, value]) => /^[A-Z]/.test(key) && isComponent(value))?.[1];
    const target = [named, mod.default, fallback].find(isComponent);
    if (target) return { path, Target: target as ComponentType };
  }
  return undefined;
}
class Boundary extends Component<{ children: ReactNode; hint: string }, { error?: string }> {
  state: { error?: string } = {};
  static getDerivedStateFromError(error: unknown) { return { error: error instanceof Error ? error.message : String(error) }; }
  render() { return this.state.error ? <pre style={{ color: '#9f1239', whiteSpace: 'pre-wrap' }}>{this.props.hint}{'\\n\\n'}{this.state.error}</pre> : this.props.children; }
}
export default function Preview() {
  const found = pick();
  if (!found) return <p>No exported React component was found in this draft.</p>;
  const { Target, path } = found;
  const file = path.replace('../', '');
  const hint = isExample(path) ? file + ' threw while rendering.'
    : file + ' was rendered without props and threw. Add an example file (for example a sibling examples/Preview.tsx) that renders it with sample props, or ask chat to add one.';
  return <Boundary hint={hint}><Target /></Boundary>;
}
`;
}

function blazorEntry(name: string) {
  return `@* Generated by ComPlix for preview only; not part of the draft. *@
@namespace ComPlixPreview.Library.Examples
@if (target is null) { <p>No Blazor component was found in this draft.</p> }
else { <ErrorBoundary><ChildContent><DynamicComponent Type="target" /></ChildContent><ErrorContent Context="error"><pre class="text-danger">@target.Name threw while rendering. It may need parameters: add an Examples/Preview.razor that passes sample values, or ask chat to add one.&#10;&#10;@error.Message</pre></ErrorContent></ErrorBoundary> }
@code {
  private const string Wanted = ${JSON.stringify(name)};
  private Type? target;
  protected override void OnInitialized()
  {
    var candidates = typeof(Preview).Assembly.GetTypes()
      .Where(type => typeof(IComponent).IsAssignableFrom(type) && !type.IsAbstract && !type.IsGenericTypeDefinition
        && type != typeof(Preview) && type.FullName != "ComPlixPreview.App" && !type.Name.StartsWith("_"))
      .ToList();
    // Example/demo/preview components pass sample parameters, so they outrank the bare component.
    target = candidates.FirstOrDefault(type => type.Name.EndsWith("Preview") || type.Name.EndsWith("Example") || type.Name.EndsWith("Demo") || type.Namespace?.EndsWith(".Examples") == true)
      ?? candidates.FirstOrDefault(type => string.Equals(type.Name, Wanted, StringComparison.OrdinalIgnoreCase))
      ?? candidates.FirstOrDefault(type => type.Namespace?.Contains(".Common") == true)
      ?? candidates.FirstOrDefault();
  }
}
`;
}

export function previewUrl(lease: SandboxLease) {
  return `https://${lease.host}/${lease.capability}/`;
}

function json(text: string): Record<string, unknown> {
  try { const value = JSON.parse(text); return value && typeof value === 'object' ? value : {}; } catch { return {}; }
}

function send(http: PreviewHttp, request: Parameters<PreviewHttp>[0]) {
  try { return http(request); } catch { return { status: 0, body: '' }; }
}

function pushBuild(http: PreviewHttp, lease: SandboxLease, revision: string, files: WorkspaceFile[]) {
  return send(http, { url: `https://${lease.host}/__build`, method: 'POST', timeoutMs: 20000,
    headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + lease.writeKey }, body: JSON.stringify({ revision, files }) });
}

/**
 * Reuses a live sandbox when possible (extending its idle timeout), otherwise creates and claims a
 * new one. Returns the lease to persist; throws only fixed messages from previewMessages or the agent's
 * own validation text.
 */
export function startSandboxBuild(http: PreviewHttp, options: {
  apiKey: string; templateId: string; appOrigin: string; existing?: SandboxLease; revision: string; files: WorkspaceFile[];
}): SandboxLease {
  const auth = { 'X-API-KEY': options.apiKey, 'Content-Type': 'application/json' };
  if (options.existing) {
    const extended = send(http, { url: `${API}/sandboxes/${options.existing.sandboxId}/timeout`, method: 'POST', headers: auth, timeoutMs: 10000, body: JSON.stringify({ timeout: PREVIEW_IDLE_SECONDS }) });
    if (extended.status >= 200 && extended.status < 300) {
      const pushed = pushBuild(http, options.existing, options.revision, options.files);
      if (pushed.status === 202) return options.existing;
      if (pushed.status === 400) throw new Error(String(json(pushed.body).error || previewMessages.agent).slice(0, 300));
    }
  }
  const created = send(http, { url: `${API}/v2/sandboxes`, method: 'POST', headers: auth, timeoutMs: 30000, body: JSON.stringify({
    // No outbound internet; inbound public traffic so the iframe can load the capability URL
    // (an iframe cannot send E2B's traffic-token header, which offline sandboxes otherwise require).
    templateID: options.templateId, timeout: PREVIEW_IDLE_SECONDS, allow_internet_access: false, network: { allowPublicTraffic: true }, secure: true, autoPause: false, metadata: { app: 'complix-preview' },
  }) });
  if (created.status === 429 || created.status === 402) throw new Error(previewMessages.quota);
  const info = json(created.body);
  const sandboxId = typeof info.sandboxID === 'string' && /^[a-z0-9-]{4,64}$/.test(info.sandboxID) ? info.sandboxID : '';
  if (created.status < 200 || created.status >= 300 || !sandboxId) throw new Error(previewMessages.create);
  const domain = typeof info.domain === 'string' && /^[a-z0-9.-]+$/.test(info.domain) ? info.domain : DOMAIN;
  const host = `${PREVIEW_PORT}-${sandboxId}.${domain}`;
  const discard = () => { send(http, { url: `${API}/sandboxes/${sandboxId}`, method: 'DELETE', headers: { 'X-API-KEY': options.apiKey }, timeoutMs: 10000 }); };
  // The agent is already running from the template snapshot; the proxy may need a moment to route.
  let claim = { status: 0, body: '' };
  for (let attempt = 0; attempt < 5 && claim.status !== 200; attempt++) {
    claim = send(http, { url: `https://${host}/__claim`, method: 'POST', headers: { 'Content-Type': 'application/json' }, timeoutMs: 10000, body: JSON.stringify({ appOrigin: options.appOrigin }) });
    if (claim.status === 409 || claim.status === 400) break;
  }
  const claimed = json(claim.body);
  if (claim.status !== 200 || typeof claimed.writeKey !== 'string' || typeof claimed.capability !== 'string' || !/^[A-Za-z0-9_-]{20,80}$/.test(claimed.capability)) {
    discard(); throw new Error(previewMessages.agent);
  }
  const lease = { sandboxId, host, writeKey: claimed.writeKey, capability: claimed.capability };
  const pushed = pushBuild(http, lease, options.revision, options.files);
  if (pushed.status !== 202) { discard(); throw new Error(pushed.status === 400 ? String(json(pushed.body).error || previewMessages.agent).slice(0, 300) : previewMessages.agent); }
  // An unreachable earlier sandbox is killed best-effort; its idle timeout bounds it otherwise.
  if (options.existing) send(http, { url: `${API}/sandboxes/${options.existing.sandboxId}`, method: 'DELETE', headers: { 'X-API-KEY': options.apiKey }, timeoutMs: 10000 });
  return lease;
}
